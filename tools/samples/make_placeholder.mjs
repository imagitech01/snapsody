#!/usr/bin/env node
// Generates the TEMPORARY placeholder sample set (task 10.3) used until the real
// tenor-sax samples are chosen and bundled (group 11). Pure synthesis, no third-party audio.
//
//   node tools/samples/make_placeholder.mjs [outDir]
//
// Default outDir: web/test/fixtures/samples/placeholder (a test fixture since task 11.4 bundled the tenor-sax set). Output is deterministic and committed
// (about 0.4 MB). Format: see web/src/core/playback/samples.ts (design D9).
//
// One 16 kHz mono 16-bit WAV per concert MIDI note 44..76 (A-flat 2 .. E5). Each file is a
// 0.15 s attack (harmonics fading in, a little breath noise) followed by a sustain section of
// an exact whole number of periods, so the loop is seamless.
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const SR = 16000
const LOWEST = 44
const HIGHEST = 76
const ATTACK_S = 0.15
const SUSTAIN_S = 0.25
const HARMONICS = [1, 0.62, 0.5, 0.34, 0.26, 0.15, 0.1, 0.06]

const here = dirname(fileURLToPath(import.meta.url))
const outDir = process.argv[2] ?? join(here, '../../web/test/fixtures/samples/placeholder')
mkdirSync(outDir, { recursive: true })

function wav(samples) {
  const data = Buffer.alloc(samples.length * 2)
  samples.forEach((s, i) => data.writeInt16LE(Math.max(-32768, Math.min(32767, Math.round(s * 32767))), i * 2))
  const header = Buffer.alloc(44)
  header.write('RIFF', 0)
  header.writeUInt32LE(36 + data.length, 4)
  header.write('WAVEfmt ', 8)
  header.writeUInt32LE(16, 16)
  header.writeUInt16LE(1, 20)
  header.writeUInt16LE(1, 22)
  header.writeUInt32LE(SR, 24)
  header.writeUInt32LE(SR * 2, 28)
  header.writeUInt16LE(2, 32)
  header.writeUInt16LE(16, 34)
  header.write('data', 36)
  header.writeUInt32LE(data.length, 40)
  return Buffer.concat([header, data])
}

const notes = {}
for (let midi = LOWEST; midi <= HIGHEST; midi++) {
  const f = 440 * 2 ** ((midi - 69) / 12)
  // Whole periods in the loop: the loop length is an integer number of samples and the tone is
  // tuned (by well under a cent) so that it fits it exactly.
  const periods = Math.max(1, Math.round(f * SUSTAIN_S))
  const loopLen = Math.round((periods * SR) / f)
  const fEff = (periods * SR) / loopLen
  const attackLen = Math.round(ATTACK_S * SR)
  const total = attackLen + loopLen
  const out = new Float64Array(total)
  let seed = midi * 7919
  const noise = () => {
    seed = (seed * 1103515245 + 12345) & 0x7fffffff
    return seed / 0x3fffffff - 1
  }
  for (let t = 0; t < total; t++) {
    let v = 0
    HARMONICS.forEach((w, k) => {
      const h = k + 1
      if (h * fEff < SR / 2 - 500) v += w * Math.sin((2 * Math.PI * h * fEff * t) / SR)
    })
    // Attack: amplitude rises over 40 ms, with breath noise that dies away by 0.1 s.
    const rise = Math.min(1, t / (0.04 * SR))
    const breath = t < 0.1 * SR ? 0.08 * (1 - t / (0.1 * SR)) * noise() : 0
    out[t] = (t < attackLen ? rise * v : v) + breath
  }
  const peak = out.reduce((m, x) => Math.max(m, Math.abs(x)), 0)
  const scaled = Array.from(out, (x) => (x / peak) * 0.5)
  const file = `${midi}.wav`
  writeFileSync(join(outDir, file), wav(scaled))
  notes[midi] = { file, sustainStart: attackLen / SR, sustainEnd: total / SR }
}

const map = {
  format: 1,
  name: 'placeholder-synth',
  license: 'Generated by tools/samples/make_placeholder.mjs; no third-party audio. Temporary until group 11 bundles the chosen tenor-sax set.',
  source: 'synthesised',
  notes,
}
writeFileSync(join(outDir, 'map.json'), `${JSON.stringify(map, null, 2)}\n`)
console.log(`wrote ${Object.keys(notes).length} samples to ${outDir}`)
