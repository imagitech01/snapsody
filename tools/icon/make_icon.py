#!/usr/bin/env python3
"""Draws the Snapsody app icon from one set of shapes and writes every file that needs it.

The mark: a staff on the app's deep green, with the note being played on the soft box the practice screen draws behind
the playing bar. Shapes live on Android's 108 x 108 adaptive-icon canvas; everything the launcher may mask
stays inside its 66-unit safe circle.

    python3 tools/icon/make_icon.py            # writes docs/design/icon/, the Android resources and web/public/favicon.svg
    python3 tools/icon/make_icon.py --preview DIR   # also renders PNG previews into DIR

Needs rsvg-convert and ImageMagick (`magick`) for the PNGs.
"""
import math, os, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

# Colours from web/src/ui/styles/tokens.css
GROUND = '#203C36'   # --surface-dark / --ink
BAR = '#33645A'      # the playing bar's box, a lighter step of the ground
NOTE = '#F7F6F1'     # --bg (cream)
PAPER = '#F7F6F1'    # splash background

def ellipse(cx, cy, rx, ry, deg):
    t = math.radians(deg)
    x1, y1 = cx + rx * math.cos(t), cy + rx * math.sin(t)
    x2, y2 = cx - rx * math.cos(t), cy - rx * math.sin(t)
    f = lambda v: f'{v:.2f}'
    return (f'M{f(x1)},{f(y1)} A{f(rx)},{f(ry)} {deg} 1 0 {f(x2)},{f(y2)} '
            f'A{f(rx)},{f(ry)} {deg} 1 0 {f(x1)},{f(y1)} Z')

def poly(*pts):
    return 'M' + ' L'.join(f'{x:.2f},{y:.2f}' for x, y in pts) + ' Z'

def rrect(x, y, w, h, r):
    return (f'M{x+r},{y} H{x+w-r} A{r},{r} 0 0 1 {x+w},{y+r} V{y+h-r} A{r},{r} 0 0 1 {x+w-r},{y+h} '
            f'H{x+r} A{r},{r} 0 0 1 {x},{y+h-r} V{y+r} A{r},{r} 0 0 1 {x+r},{y} Z')

# --- the mark, on the 108-unit canvas (centre 54,54) ---
# A five-line staff, a barline, a quiet note in the bar before, and the note being played on the soft box the practice
# screen draws behind the playing bar. The staff runs on past the safe circle on purpose: a round mask cuts it off like
# a stave going on beyond the page.
LINE = '#7A9A91'     # staff lines and barline
PAST = '#A9C0B8'     # the note already played
LINE_W = 2.2
staff_y = [37.0, 45.0, 53.0, 61.0, 69.0]

def note(cx, cy, rx, ry, stem_w, stem_top):
    sx = cx + rx * math.cos(math.radians(-22)) - stem_w + 0.35
    return [ellipse(cx, cy, rx, ry, -22), poly((sx, stem_top), (sx + stem_w, stem_top), (sx + stem_w, cy - 1), (sx, cy - 1))]

bar = rrect(52.0, 28.0, 25.0, 50.0, 6.0)
lines = [rrect(18.0, y - LINE_W / 2, 72.0, LINE_W, LINE_W / 2) for y in staff_y]
barline = rrect(35.0, staff_y[0] - LINE_W / 2, LINE_W, staff_y[-1] - staff_y[0] + LINE_W, LINE_W / 2)
past = ellipse(43.5, 57.0, 6.9, 5.0, -22)
playing = note(63.5, 61.0, 7.6, 5.5, 2.9, 33.0)

# (path, colour) from back to front; the monochrome layer (themed icons) keeps the staff and the notes
layers = [(bar, BAR)] + [(d, LINE) for d in lines] + [(barline, LINE), (past, PAST)] + [(d, NOTE) for d in playing]
mono = lines + [barline, past] + playing

def svg(size=None, ground=True, rounded=False):
    s = f' width="{size}" height="{size}"' if size else ''
    g = ''
    if ground:
        g = f'<rect width="108" height="108" rx="{24 if rounded else 0}" fill="{GROUND}"/>'
    body = ''.join(f'<path d="{d}" fill="{c}"/>' for d, c in layers)
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108"{s}>{g}{body}</svg>\n'

def vector(paths):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by tools/icon/make_icon.py: edit that script, not this file. -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="108dp" android:height="108dp"',
           '    android:viewportWidth="108" android:viewportHeight="108">']
    for d, colour in paths:
        out.append(f'    <path android:fillColor="{colour}" android:pathData="{d}"/>')
    out.append('</vector>\n')
    return '\n'.join(out)

def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write(text)
    return path

def png(svg_text, out, px):
    with tempfile.NamedTemporaryFile('w', suffix='.svg', delete=False) as f:
        f.write(svg_text)
    subprocess.run(['rsvg-convert', '-w', str(px), '-h', str(px), '-o', out, f.name], check=True)
    os.unlink(f.name)

def main():
    res = 'android/app/src/main/res'
    write('docs/design/icon/snapsody-icon.svg', svg(rounded=True))
    write('docs/design/icon/snapsody-foreground.svg', svg(ground=False))
    write('web/public/favicon.svg', svg(rounded=True))
    write(f'{res}/drawable/ic_launcher_foreground.xml', vector(layers))
    write(f'{res}/drawable/ic_launcher_monochrome.xml', vector([(d, '#FFFFFFFF') for d in mono]))
    write(f'{res}/values/ic_launcher_background.xml',
          '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
          f'    <color name="ic_launcher_background">{GROUND}</color>\n</resources>\n')
    adaptive = ('<?xml version="1.0" encoding="utf-8"?>\n'
                '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                '    <background android:drawable="@color/ic_launcher_background"/>\n'
                '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
                '    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n'
                '</adaptive-icon>\n')
    write(f'{res}/mipmap-anydpi-v26/ic_launcher.xml', adaptive)
    write(f'{res}/mipmap-anydpi-v26/ic_launcher_round.xml', adaptive)
    # Bitmaps for anything that does not read the adaptive icon (the store listing, older tools).
    for dpi, scale in [('mdpi', 1), ('hdpi', 1.5), ('xhdpi', 2), ('xxhdpi', 3), ('xxxhdpi', 4)]:
        d = os.path.join(ROOT, res, f'mipmap-{dpi}')
        os.makedirs(d, exist_ok=True)
        png(svg(rounded=True), os.path.join(d, 'ic_launcher.png'), int(48 * scale))
        png(svg(rounded=True), os.path.join(d, 'ic_launcher_round.png'), int(48 * scale))
    png(svg(rounded=False), os.path.join(ROOT, 'docs/design/icon/snapsody-icon-512.png'), 512)
    # The launch screen: the icon in the middle of the app's paper colour.
    icon = os.path.join(tempfile.gettempdir(), 'snapsody-splash-icon.png')
    png(svg(rounded=True), icon, 288)
    for folder in sorted(os.listdir(os.path.join(ROOT, res))):
        target = os.path.join(ROOT, res, folder, 'splash.png')
        if not os.path.exists(target):
            continue
        w, h = subprocess.run(['magick', 'identify', '-format', '%w %h', target],
                              check=True, capture_output=True, text=True).stdout.split()
        side = max(96, min(int(w), int(h)) // 4)
        subprocess.run(['magick', '-size', f'{w}x{h}', f'xc:{PAPER}', '(', icon, '-resize', f'{side}x{side}', ')',
                        '-gravity', 'center', '-composite', '-strip', target], check=True)
    if '--preview' in sys.argv:
        out = sys.argv[sys.argv.index('--preview') + 1]
        os.makedirs(out, exist_ok=True)
        png(svg(rounded=True), os.path.join(out, 'icon-512.png'), 512)
        png(svg(rounded=True), os.path.join(out, 'icon-48.png'), 48)

if __name__ == '__main__':
    main()
